/**
 * Build-time only. Converts Natural Earth land geometry (public domain, via world-atlas)
 * into a single equirectangular SVG path so the runtime ships zero map dependencies.
 * Run with: node scripts/gen-world.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land).features[0];

const W = 1000;
const H = 500;
const project = ([lon, lat]) => [((lon + 180) / 360) * W, ((90 - lat) / 180) * H];

// Drop slivers and Antarctica (adds visual weight, no commercial relevance).
const MIN_AREA = 1.1;
const ringArea = (ring) => {
  let a = 0;
  for (let i = 0, n = ring.length - 1; i < n; i++) {
    a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  }
  return Math.abs(a / 2);
};

const round = (n) => Math.round(n * 10) / 10;

// Ramer–Douglas–Peucker: keeps silhouette, drops redundant vertices.
const perp = (p, a, b) => {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len = Math.hypot(dx, dy);
  if (len === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / len;
};
const simplify = (pts, eps) => {
  if (pts.length < 3) return pts;
  let maxD = 0;
  let idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = perp(pts[i], pts[0], pts[pts.length - 1]);
    if (d > maxD) { maxD = d; idx = i; }
  }
  if (maxD <= eps) return [pts[0], pts[pts.length - 1]];
  return [
    ...simplify(pts.slice(0, idx + 1), eps).slice(0, -1),
    ...simplify(pts.slice(idx), eps),
  ];
};

const rings = [];
for (const geom of land.geometry.coordinates) {
  const polygons = land.geometry.type === "MultiPolygon" ? geom : [geom];
  for (const ring of polygons) {
    if (!Array.isArray(ring[0])) continue;
    const projected = ring.map(project);
    if (ringArea(projected) < MIN_AREA) continue;
    // Antarctica: everything below 60°S
    if (projected.every(([, y]) => y > ((90 + 60) / 180) * H)) continue;
    rings.push(simplify(projected, 0.55));
  }
}

const d = rings
  .map((ring) => {
    let out = "";
    let prev = null;
    ring.forEach((pt, i) => {
      const x = round(pt[0]);
      const y = round(pt[1]);
      if (i === 0) {
        out += `M${x} ${y}`;
      } else if (prev && (Math.abs(x - prev[0]) > 0.8 || Math.abs(y - prev[1]) > 0.8)) {
        out += `L${x} ${y}`;
      } else {
        return;
      }
      prev = [x, y];
    });
    return out + "Z";
  })
  .join("");

writeFileSync(
  "src/lib/world-path.ts",
  `// AUTO-GENERATED by scripts/gen-world.mjs — do not edit by hand.
// Source: Natural Earth 110m land (public domain) via the world-atlas package.
// Equirectangular projection, viewBox 0 0 ${W} ${H}.

export const WORLD_VIEWBOX = "0 0 ${W} ${H}";

export const WORLD_LAND_PATH =
  "${d}";
`
);

console.log("rings:", rings.length, "path chars:", d.length);
